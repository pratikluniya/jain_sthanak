const DICTS: Record<Lang, Dict> = { mr, hi, en };

export function asLang(v: string | null | undefined): Lang {
  return v === "hi" || v === "en" ? v : "mr";
}

export function getLang(): Lang {
  return asLang(cookies().get("lang")?.value);
}

export function getDict(lang?: Lang): Dict {
  return DICTS[lang ?? getLang()];
}

/** Marathi dictionary, used for receipts (receipts are always Marathi). */
export const exportDict: Dict = mr;

/** Dictionary for an export (voter / member list) in the chosen language. */
export function exportDictFor(lang: Lang): Dict {
  return DICTS[lang];
}
